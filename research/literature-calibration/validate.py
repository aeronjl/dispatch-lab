def record(name, condition, scope):
    checks.append(dict(name=name, outcome="passed" if bool(condition) else "failed", scope=scope))


def read(name):
    return json.loads((HERE / name).read_text())


def raises(call):
    try:
        call()
    except ValueError:
        return True
    return False


